"""Deterministic offline discovery backend — **explicitly not live**.

Used by the offline test suite and by `--mode offline_fixture` runs. It is a
pure function of ``(parent workspace, history)`` — never of wall-clock time,
thread interleaving or a hidden RNG — which makes it order-independent under
parallel batches and therefore reproducible. It writes *real, runnable* code
that the fixed evaluator genuinely grades — the improvement ladder is a real
improvement ladder, not a fabricated score.

There is one recipe per bundled task. A task with no recipe raises rather than
falling back to an unrelated task's ladder.

Results from this backend carry ``backend_id="fixture"`` and ``is_live=False``;
the controller refuses to merge them into live statistics
(`RunMode.OFFLINE_FIXTURE` vs `RunMode.LIVE`).
"""
from __future__ import annotations

import re
import shutil
import time
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path

from .base import GeneratedAttempt, HistoryEntry, TaskSpec, digest_file, digest_text

_MARKER = re.compile(r"^#\s*STRATEGY:\s*([a-z_]+)\s*$", re.MULTILINE)


@dataclass(frozen=True)
class Recipe:
    """How the fixture climbs one task's ladder."""

    header: str
    root_strategy: str
    ladder: tuple[str, ...]
    bodies: Mapping[str, str]

    def render(self, strategy: str) -> str:
        return self.header.format(strategy=strategy) + self.bodies[strategy]


# ---------------------------------------------------------------------------
# knapsack
# ---------------------------------------------------------------------------

_KNAPSACK_HEADER = '''"""Knapsack candidate (fixture-generated).

Generated by dream_rsi.adapters.fixture for OFFLINE testing only.
This backend is NOT a model and its results are never reported as live.
"""
from __future__ import annotations

# STRATEGY: {strategy}


'''

_KNAPSACK_BODIES: dict[str, str] = {
    "greedy_value": '''def solve(weights: list[int], values: list[int], capacity: int) -> list[int]:
    """Pack the most valuable items first, if they still fit."""
    order = sorted(range(len(weights)), key=lambda i: values[i], reverse=True)
    chosen: list[int] = []
    remaining = capacity
    for index in order:
        if weights[index] <= remaining:
            chosen.append(index)
            remaining -= weights[index]
    return sorted(chosen)
''',
    "greedy_ratio": '''def solve(weights: list[int], values: list[int], capacity: int) -> list[int]:
    """Pack by value density (value per unit weight), highest first."""
    order = sorted(
        range(len(weights)),
        key=lambda i: values[i] / weights[i],
        reverse=True,
    )
    chosen: list[int] = []
    remaining = capacity
    for index in order:
        if weights[index] <= remaining:
            chosen.append(index)
            remaining -= weights[index]
    return sorted(chosen)
''',
    "exact_dp": '''def solve(weights: list[int], values: list[int], capacity: int) -> list[int]:
    """Exact 0/1 knapsack by dynamic programming, with backtracking."""
    count = len(weights)
    table = [[0] * (capacity + 1) for _ in range(count + 1)]
    for item in range(1, count + 1):
        weight = weights[item - 1]
        value = values[item - 1]
        previous = table[item - 1]
        current = table[item]
        for cap in range(capacity + 1):
            best = previous[cap]
            if weight <= cap:
                candidate = previous[cap - weight] + value
                if candidate > best:
                    best = candidate
            current[cap] = best
    chosen: list[int] = []
    cap = capacity
    for item in range(count, 0, -1):
        if table[item][cap] != table[item - 1][cap]:
            chosen.append(item - 1)
            cap -= weights[item - 1]
    return sorted(chosen)
''',
}

_KNAPSACK = Recipe(
    header=_KNAPSACK_HEADER,
    root_strategy="first_fit",
    # The ladder the fixture climbs, one rung per generation.
    ladder=("greedy_value", "greedy_ratio", "exact_dp"),
    bodies=_KNAPSACK_BODIES,
)


RECIPES: dict[str, Recipe] = {"knapsack": _KNAPSACK}


def recipe_for(task_id: str) -> Recipe:
    try:
        return RECIPES[task_id]
    except KeyError:
        raise KeyError(
            f"no fixture recipe for task {task_id!r}; known: {', '.join(sorted(RECIPES))}"
        ) from None


def current_strategy(text: str, recipe: Recipe | None = None) -> str:
    recipe = recipe or _KNAPSACK
    match = _MARKER.search(text)
    return match.group(1) if match else recipe.root_strategy


def next_strategy(
    text: str, *, recipe: Recipe | None = None, rungs: Sequence[str] | None = None
) -> str | None:
    """Return the next rung, or ``None`` when already at the top.

    ``rungs`` overrides the recipe's ladder; :func:`rungs_for` uses that to let
    each world start further up, so ``H_t`` is not degenerate.
    """
    recipe = recipe or _KNAPSACK
    rungs = recipe.ladder if rungs is None else tuple(rungs)
    here = current_strategy(text, recipe)
    if here not in rungs:
        return rungs[0] if rungs else None
    index = rungs.index(here)
    if index + 1 < len(rungs):
        return rungs[index + 1]
    return None


def rungs_for(history: Sequence[HistoryEntry], recipe: Recipe | None = None) -> tuple[str, ...]:
    """World ``t`` skips the rungs that the ``t`` earlier worlds already climbed.

    §3 starts every world from the *same* fixed initial workspace, and this
    backend is deterministic, so without this every world would produce a
    byte-identical tree: ``H_t`` would be degenerate and the offline suite could
    not tell a correct cross-world aggregation from a broken one. Reading
    ``history`` — the read-only public record of finished worlds that §3 hands
    the discovery agent anyway — is the honest fix. It stays a pure function of
    ``(parent workspace, history)``, so parallel batches remain order-independent.
    """
    recipe = recipe or _KNAPSACK
    return recipe.ladder[min(len(history), len(recipe.ladder)) :]


def render_candidate(strategy: str, recipe: Recipe | None = None) -> str:
    return (recipe or _KNAPSACK).render(strategy)


class FixtureDiscoveryBackend:
    """Deterministic, offline, order-independent. ``is_live`` is False."""

    backend_id = "fixture"
    is_live = False

    def __init__(self, *, seed_workspace: Path | None = None) -> None:
        self.seed_workspace = seed_workspace

    def generate(
        self,
        *,
        task: TaskSpec,
        parent_workspace: Path,
        history: Sequence[HistoryEntry],
        output_workspace: Path,
        invocation_id: str,
    ) -> GeneratedAttempt:
        started = time.monotonic()
        parent_workspace = Path(parent_workspace)
        output_workspace = Path(output_workspace)
        output_workspace.mkdir(parents=True, exist_ok=True)

        recipe = recipe_for(task.task_id)
        entry = parent_workspace / task.entry_filename
        parent_text = entry.read_text(encoding="utf-8") if entry.is_file() else ""
        strategy = next_strategy(parent_text, recipe=recipe, rungs=rungs_for(history, recipe))

        if strategy is None:
            # Already at the top of the ladder: reproduce the parent unchanged.
            target = output_workspace / task.entry_filename
            shutil.copyfile(entry, target)
            summary = "fixture: no further rung available; candidate reproduced unchanged"
        else:
            target = output_workspace / task.entry_filename
            target.write_text(recipe.render(strategy), encoding="utf-8")
            summary = f"fixture: advanced candidate to strategy {strategy!r}"

        duration = time.monotonic() - started
        return GeneratedAttempt(
            invocation_id=invocation_id,
            backend_id=self.backend_id,
            model="deterministic-fixture",
            workspace_path=output_workspace,
            entry_file_digest=digest_file(target),
            succeeded=True,
            duration_s=duration,
            error_type=None,
            summary=summary,
            session_id=None,
            raw_response_digest=digest_text(summary),
            extra={"is_live": False, "strategy": strategy or current_strategy(parent_text, recipe)},
        )


