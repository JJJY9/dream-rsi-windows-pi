"""Deterministic offline discovery backend — **explicitly not live**.

Used by the offline test suite and by `--mode offline_fixture` runs. It is a
pure function of ``(parent workspace, history)`` — never of wall-clock time,
thread interleaving or a hidden RNG — which makes it order-independent under
parallel batches and therefore reproducible. It writes *real, runnable* code
that the fixed evaluator genuinely grades — the improvement ladder is a real
improvement ladder, not a fabricated score.

There is one recipe per bundled task. A task with no recipe raises rather than
falling back to an unrelated task's ladder.

Results from this backend carry ``backend_id="fixture"`` and ``is_live=False``;
the controller refuses to merge them into live statistics
(`RunMode.OFFLINE_FIXTURE` vs `RunMode.LIVE`).
"""
from __future__ import annotations

import re
import shutil
import time
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path

from .base import GeneratedAttempt, HistoryEntry, TaskSpec, digest_file, digest_text

_MARKER = re.compile(r"^#\s*STRATEGY:\s*([a-z_]+)\s*$", re.MULTILINE)


@dataclass(frozen=True)
class Recipe:
    """How the fixture climbs one task's ladder."""

    header: str
    root_strategy: str
    ladder: tuple[str, ...]
    bodies: Mapping[str, str]

    def render(self, strategy: str) -> str:
        return self.header.format(strategy=strategy) + self.bodies[strategy]


