_CIRCLE_PACKING_HEADER = '''"""Circle-packing candidate (fixture-generated).

Generated by dream_rsi.adapters.fixture for OFFLINE testing only.
This backend is NOT a model and its results are never reported as live.
"""
from __future__ import annotations

import math

# STRATEGY: {strategy}


'''

_CIRCLE_PACKING_BODIES: dict[str, str] = {
    "hex_rows": '''def construct() -> list[tuple[float, float, float]]:
    """Six staggered rows (5-4-5-4-5-3) of equal circles, hexagonally spaced
    at r = 0.09: every neighbour pair touches at distance 2r and the whole
    arrangement clears the square border. Sum of radii = 2.34, far better
    than the shipped ring arrangement (~0.957)."""
    r = 0.09
    dy = r * math.sqrt(3.0)
    y = 0.5 - 2.5 * dy
    circles: list[tuple[float, float, float]] = []
    for k, count in enumerate((5, 4, 5, 4, 5, 3)):
        x0 = 0.5 - 4.0 * r + (r if k % 2 else 0.0)
        for c in range(count):
            circles.append((x0 + 2.0 * r * c, y, r))
        y += dy
    return circles
''',
    "hex_max": '''def construct() -> list[tuple[float, float, float]]:
    """The same hexagonal layout with the equal radius pushed to its exact
    geometric maximum: the height constraint (five row gaps of sqrt(3) r
    plus two border margins) makes r(2 + 5 sqrt(3)) = 1, so
    r = 1 / (2 + 5 sqrt(3)) ~= 0.0938064 and the sum of radii is ~2.43897.
    Both the border and every pair stay satisfied with equality at the tight
    rows, so this is the best possible equal-radius packing of this shape."""
    r = 1.0 / (2.0 + 5.0 * math.sqrt(3.0))
    dy = r * math.sqrt(3.0)
    y = 0.5 - 2.5 * dy
    circles: list[tuple[float, float, float]] = []
    for k, count in enumerate((5, 4, 5, 4, 5, 3)):
        x0 = 0.5 - 4.0 * r + (r if k % 2 else 0.0)
        for c in range(count):
            circles.append((x0 + 2.0 * r * c, y, r))
        y += dy
    return circles
''',
}

_CIRCLE_PACKING = Recipe(
    header=_CIRCLE_PACKING_HEADER,
    root_strategy="rings",
    ladder=("hex_rows", "hex_max"),
    bodies=_CIRCLE_PACKING_BODIES,
)


RECIPES: dict[str, Recipe] = {
    "knapsack": _KNAPSACK,
    "packing": _PACKING,
    "circle_packing": _CIRCLE_PACKING,
}


def recipe_for(task_id: str) -> Recipe:
    try:
        return RECIPES[task_id]
    except KeyError:
        raise KeyError(
            f"no fixture recipe for task {task_id!r}; known: {', '.join(sorted(RECIPES))}"
        ) from None


def current_strategy(text: str, recipe: Recipe | None = None) -> str:
    recipe = recipe or _KNAPSACK
    match = _MARKER.search(text)
    return match.group(1) if match else recipe.root_strategy


def next_strategy(
    text: str, *, recipe: Recipe | None = None, rungs: Sequence[str] | None = None
) -> str | None:
    """Return the next rung, or ``None`` when already at the top.

    ``rungs`` overrides the recipe's ladder; :func:`rungs_for` uses that to let
    each world start further up, so ``H_t`` is not degenerate.
    """
    recipe = recipe or _KNAPSACK
    rungs = recipe.ladder if rungs is None else tuple(rungs)
    here = current_strategy(text, recipe)
    if here not in rungs:
        return rungs[0] if rungs else None
    index = rungs.index(here)
    if index + 1 < len(rungs):
        return rungs[index + 1]
    return None


def rungs_for(history: Sequence[HistoryEntry], recipe: Recipe | None = None) -> tuple[str, ...]:
    """World ``t`` skips the rungs that the ``t`` earlier worlds already climbed.

    §3 starts every world from the *same* fixed initial workspace, and this
    backend is deterministic, so without this every world would produce a
    byte-identical tree: ``H_t`` would be degenerate and the offline suite could
    not tell a correct cross-world aggregation from a broken one. Reading
    ``history`` — the read-only public record of finished worlds that §3 hands
    the discovery agent anyway — is the honest fix. It stays a pure function of
    ``(parent workspace, history)``, so parallel batches remain order-independent.
    """
    recipe = recipe or _KNAPSACK
    return recipe.ladder[min(len(history), len(recipe.ladder)) :]


def render_candidate(strategy: str, recipe: Recipe | None = None) -> str:
    return (recipe or _KNAPSACK).render(strategy)


class FixtureDiscoveryBackend:
    """Deterministic, offline, order-independent. ``is_live`` is False."""

    backend_id = "fixture"
    is_live = False

    def __init__(self, *, seed_workspace: Path | None = None) -> None:
        self.seed_workspace = seed_workspace

    def generate(
        self,
        *,
        task: TaskSpec,
        parent_workspace: Path,
        history: Sequence[HistoryEntry],
        output_workspace: Path,
        invocation_id: str,
    ) -> GeneratedAttempt:
        started = time.monotonic()
        parent_workspace = Path(parent_workspace)
        output_workspace = Path(output_workspace)
        output_workspace.mkdir(parents=True, exist_ok=True)

        recipe = recipe_for(task.task_id)
        entry = parent_workspace / task.entry_filename
        parent_text = entry.read_text(encoding="utf-8") if entry.is_file() else ""
        strategy = next_strategy(parent_text, recipe=recipe, rungs=rungs_for(history, recipe))

        if strategy is None:
            # Already at the top of the ladder: reproduce the parent unchanged.
            target = output_workspace / task.entry_filename
            shutil.copyfile(entry, target)
            summary = "fixture: no further rung available; candidate reproduced unchanged"
        else:
            target = output_workspace / task.entry_filename
            target.write_text(recipe.render(strategy), encoding="utf-8")
            summary = f"fixture: advanced candidate to strategy {strategy!r}"

        duration = time.monotonic() - started
        return GeneratedAttempt(
            invocation_id=invocation_id,
            backend_id=self.backend_id,
            model="deterministic-fixture",
            workspace_path=output_workspace,
            entry_file_digest=digest_file(target),
            succeeded=True,
            duration_s=duration,
            error_type=None,
            summary=summary,
            session_id=None,
            raw_response_digest=digest_text(summary),
            extra={"is_live": False, "strategy": strategy or current_strategy(parent_text, recipe)},
        )


