_KNAPSACK_HEADER = '''"""Knapsack candidate (fixture-generated).

Generated by dream_rsi.adapters.fixture for OFFLINE testing only.
This backend is NOT a model and its results are never reported as live.
"""
from __future__ import annotations

# STRATEGY: {strategy}


'''

_KNAPSACK_BODIES: dict[str, str] = {
    "greedy_value": '''def solve(weights: list[int], values: list[int], capacity: int) -> list[int]:
    """Pack the most valuable items first, if they still fit."""
    order = sorted(range(len(weights)), key=lambda i: values[i], reverse=True)
    chosen: list[int] = []
    remaining = capacity
    for index in order:
        if weights[index] <= remaining:
            chosen.append(index)
            remaining -= weights[index]
    return sorted(chosen)
''',
    "greedy_ratio": '''def solve(weights: list[int], values: list[int], capacity: int) -> list[int]:
    """Pack by value density (value per unit weight), highest first."""
    order = sorted(
        range(len(weights)),
        key=lambda i: values[i] / weights[i],
        reverse=True,
    )
    chosen: list[int] = []
    remaining = capacity
    for index in order:
        if weights[index] <= remaining:
            chosen.append(index)
            remaining -= weights[index]
    return sorted(chosen)
''',
    "exact_dp": '''def solve(weights: list[int], values: list[int], capacity: int) -> list[int]:
    """Exact 0/1 knapsack by dynamic programming, with backtracking."""
    count = len(weights)
    table = [[0] * (capacity + 1) for _ in range(count + 1)]
    for item in range(1, count + 1):
        weight = weights[item - 1]
        value = values[item - 1]
        previous = table[item - 1]
        current = table[item]
        for cap in range(capacity + 1):
            best = previous[cap]
            if weight <= cap:
                candidate = previous[cap - weight] + value
                if candidate > best:
                    best = candidate
            current[cap] = best
    chosen: list[int] = []
    cap = capacity
    for item in range(count, 0, -1):
        if table[item][cap] != table[item - 1][cap]:
            chosen.append(item - 1)
            cap -= weights[item - 1]
    return sorted(chosen)
''',
}

_KNAPSACK = Recipe(
    header=_KNAPSACK_HEADER,
    root_strategy="first_fit",
    # The ladder the fixture climbs, one rung per generation.
    ladder=("greedy_value", "greedy_ratio", "exact_dp"),
    bodies=_KNAPSACK_BODIES,
)


