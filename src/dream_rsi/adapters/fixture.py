_PACKING_HEADER = '''"""Packing candidate (fixture-generated).

Generated by dream_rsi.adapters.fixture for OFFLINE testing only.
This backend is NOT a model and its results are never reported as live.
"""
from __future__ import annotations

import math

# STRATEGY: {strategy}


'''

_PACKING_BODIES: dict[str, str] = {
    "wide_shift": '''def construct() -> list[tuple[float, float]]:
    """Six rows of five points; odd rows shifted by half the in-row spacing.

    With w = 0.21 the diagonal distance between adjacent rows is
    sqrt((w/2)^2 + 0.2^2) ~= 0.226 > w, so the minimum pairwise distance is
    the in-row spacing w -- strictly better than the plain 0.2 lattice.
    """
    w = 0.21
    shift = w / 2.0
    points: list[tuple[float, float]] = []
    for r in range(6):
        y = r / 5.0
        x0 = shift if r % 2 else 0.0
        for c in range(5):
            points.append((x0 + c * w, y))
    return points
''',
    "brick": '''def construct() -> list[tuple[float, float]]:
    """Closed-form staggered "brick wall": rows of five points, odd rows
    shifted so their last point touches x = 1, with the in-row spacing w
    equal to the nearest diagonal spacing pinned by

        w^2 = (1 - 4w)^2 + (1/5)^2  =>  w = (8 - sqrt(1.6)) / 30 ~= 0.224503.

    Every pair is then at distance >= w, achieved both within rows and
    diagonally between adjacent rows.
    """
    w = (8.0 - math.sqrt(1.6)) / 30.0
    shift = 1.0 - 4.0 * w
    points: list[tuple[float, float]] = []
    for r in range(6):
        y = r / 5.0
        x0 = shift if r % 2 else 0.0
        for c in range(5):
            points.append((x0 + c * w, y))
    return points
''',
}

_PACKING = Recipe(
    header=_PACKING_HEADER,
    root_strategy="lattice",
    ladder=("wide_shift", "brick"),
    bodies=_PACKING_BODIES,
)


